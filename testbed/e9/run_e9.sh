# The full-history initial seal (A5) holds the whole recorder's rows and roots in memory during the first poll; two
# monitors doing it at once exceeded the Docker VM's memory in the smoke run (OOM kill, then a restart loop). So the
# monitors start one after the other: the second only when the first has sealed and anchored its history (its poll
# counter has advanced SEAL_SETTLE_POLLS polls past the first record, every append ok, no restart).
SEAL_WAIT_MAX_S=${HPR_E9_SEAL_WAIT_MAX_S:-5400}
SEAL_SETTLE_POLLS=${HPR_E9_SEAL_SETTLE_POLLS:-6}
wait_sealed() {   # $1 monitor container, $2 anchor container -> 0 when its initial seal is anchored
  local end=$(( $(date -u +%s) + SEAL_WAIT_MAX_S )) t0; t0=$(date -u +%s)
  while [ "$(date -u +%s)" -lt "$end" ]; do
    local st; st=$(docker exec "$2" python -c '
import json
n=mx=mn=0; ok=True
for l in open("/anchor/chain.jsonl"):
    p=json.loads(l).get("payload") or {}
    if p.get("observer")!="external-monitor": continue
    n+=1; s=int(p.get("seq_local",0)); mx=max(mx,s); mn=s if mn==0 else min(mn,s)
print(n, mn, mx)' 2>/dev/null)
    local rc; rc=$(docker inspect "$1" --format '{{.RestartCount}}')
    set -- "$1" "$2" $st
    if [ "${3:-0}" -gt 0 ] && [ $(( ${5:-0} - ${4:-0} )) -ge "$SEAL_SETTLE_POLLS" ]; then
      # the container's own peak memory (cgroup v2 memory.peak: every byte the monitor held since it started)
      local peak; peak=$(docker exec "$1" cat /sys/fs/cgroup/memory.peak 2>/dev/null | tr -d '\n'); [[ "$peak" =~ ^[0-9]+$ ]] || peak=null
      note "  $1: initial seal anchored after $(( $(date -u +%s) - t0 ))s ($3 records, polls ${4}-${5}, restarts $rc, peak memory $peak B, now $(docker stats --no-stream --format '{{.MemUsage}}' "$1"))"
      ev initial_seal "\"monitor\": \"$1\", \"wait_s\": $(( $(date -u +%s) - t0 )), \"records\": $3, \"restarts\": $rc, \"memory_peak_bytes\": $peak"
      return 0
    fi
    wsleep 10
  done
  note "  $1: initial seal NOT anchored within ${SEAL_WAIT_MAX_S}s (restarts $(docker inspect "$1" --format '{{.RestartCount}}'))"
  ev initial_seal "\"monitor\": \"$1\", \"wait_s\": null, \"restarts\": $(docker inspect "$1" --format '{{.RestartCount}}')"
  return 1
}
