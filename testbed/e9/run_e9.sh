#!/bin/bash
# E9 (round 13), part B: the deployed configuration for SEVEN DAYS on the lab installation (hpr-hass, Home Assistant
# 2026.7.4, virtual devices, purge_keep_days 30, auto_purge on), drafts/round13/E9_DESIGN.md section B.
#
# Two monitors, both stable columns + coverage + Ed25519 record signatures + escrow + name-map digest (the hub's
# .storage on the read-only configuration mount) + per-row binding + the full-history initial seal:
#   M-direct  HOMEPROV_READ=direct  (one read-only SQLite connection, one read transaction per poll)   [E9 A4]
#   M-copy    HOMEPROV_READ=copy    (copy the database and WAL, as in E8)
# Each has its own linked anchor (append key, separate operator key, tagged replies) and a head witness (python3 on the
# Mac, outside Docker's VM, loopback only). Fresh keys; only fingerprints are recorded.
#
# The week follows a schedule generated by testbed/e9/e9ops.py (real: from HPR_E9_START, default 2026-10-11T12:00:00Z):
# each day an attack batch at 14:00 UTC (homeprov_ec PU, PSR; homeprov_e7 INS-L, BD-S; HPR_E9_TRIALS per arm), an
# end-of-day recorder snapshot at 12:00:30; each night a sleep guard at 03:40, a snapshot at 03:55, an operator PURGE
# marker posted at 04:10:00 (issuer started 04:07) for the hub's own 04:12 purge, a snapshot at 04:45. Day 2: one
# planned hub restart (20:00). Day 3: the name-map session (17:00: a benign entity rename under an operator RENAME marker;
# the person re-link as a MOVE of a household account from its person to a person without an account, declared and
# moved back under RENAME markers; then the same move as the ATTACK, no row edit, no marker; its declared move back;
# a SWAP of two persons' accounts only on a hub without the account-less person), through the E6 in-hub harness
# homeprov_e6 (never released). Day 4: a backup at 20:00 and Home Assistant's own restore of the recorder at
# 20:30 (.HA_RESTORE, restore_database=true, restore_homeassistant=false) between an operator RESTORE marker and an
# operator RESTORE_DONE marker; the archive is held outside the hub and placed (and its copy checked) with the hub stopped.
# A background host log records every wall-clock gap (host sleep), the Docker VM's clock offset, every hub start, power
# source and lid state, and each monitor's /proc/1/io. Every wait is on the WALL clock (E2_PURGE_DIAGNOSIS.md).
#
#   Real run (the LEAD starts it on 2026-10-11 between 09:00 and 11:00 UTC; the Mac on power, lid open, awake):
#       mkdir -p <research-dir>/HOMEPROV-P13-exp/e9
#       nohup caffeinate -i -s -m testbed/e9/run_e9.sh e9_main > <research-dir>/HOMEPROV-P13-exp/e9/e9_main.out 2>&1 &
#   Smoke run on the scratch stack (testbed/e9/smoke_stack.sh up first; outputs outside exp/out):
#       HPR_E9_SCRATCH=1 HPR_E9_PREFIX=e9s HPR_E9_HUB=e9s-hass HPR_E9_NET=e9s-net HPR_E9_CFGVOL=e9s-config \
#       HPR_E9_DEVICES=e9s-devices HPR_E9_BROKER=e9s-broker HPR_E9_STOCK_MONITOR= HPR_E9_STOCK_ANCHOR= \
#       HPR_E9_OUT=<research-dir>/HOMEPROV-P13-exp/e9/smoke/out HPR_E9_SP=<research-dir>/HOMEPROV-P13-exp/e9/smoke/e9s_smoke \
#       HPR_E9_SMOKE=1 testbed/e9/run_e9.sh e9s_smoke
#
# What it does to the default deployment, by design: stops and renames hpr-monitor/hpr-anchord for the week (restored
# on exit); adds `person:` to configuration.yaml and creates one person per household account (setup, before the week);
# installs and removes the attack integrations per batch (three hub restarts a day); one planned restart; one restore;
# recorder snapshots read OUTSIDE the hub (a throwaway container on the read-only mount, SQLite's online backup API
# from a read-only connection; the hub's /tmp only as a recorded fallback). Restores
# configuration.yaml byte for byte at the end (the persons stay in .storage/person, inert without `person:`).
# Never overwrites an output. Scratch testing: every target is overridable by env (HPR_E9_*); HPR_E9_SCRATCH=1 skips the
# E2-night, clock, power and start-time guards, which protect only the shared real deployment.
set -u

# ---- targets (real-deployment defaults; overridden for the scratch stack) ---------------------------------------
REPO="${ARTIFACT_ROOT:-$(cd "$(dirname "$0")/../.." && pwd)}"; export ARTIFACT_ROOT="$REPO"
OUT=${HPR_E9_OUT:-$REPO/exp/out}
