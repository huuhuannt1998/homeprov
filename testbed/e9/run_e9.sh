# ---- recorder snapshots: SQLite's online backup API inside the hub, from a read-only connection ---------------------
snapshot_db() {   # $1 = label -> $SP/snapshots/$1.db ; the time at the START of the backup is the snapshot time
  # OUTSIDE THE HUB: a throwaway container (the monitor image) on the READ-ONLY mount of the hub's configuration volume
  # runs SQLite's online backup API from a read-only connection with read-only shared memory (mode=ro&readonly_shm=1, as
  # the direct-read monitor reads the live recorder: one read transaction, a consistent snapshot while the hub writes)
  # into the run directory; the copy never sits in the hub container. Only if that fails three times does the snapshot
  # fall back to the earlier path (backup inside the hub to its /tmp, copied out), recorded as such in the event.
  local lab=$1 dst="$SP/snapshots/$1.db" res="" try method=readonly_mount t0 t1 qc=null
  rm -f "$dst.part"
  for try in 1 2 3; do
    res=$(docker run --rm -v "$CFGVOL":/cfg:ro -v "$SP/snapshots":/out --entrypoint python "$MON_IMG" -c '
import json, sqlite3, sys, time
dst = "/out/%s.db.part" % sys.argv[1]
t0 = time.time()
s = sqlite3.connect("file:/cfg/home-assistant_v2.db?mode=ro&readonly_shm=1", uri=True, timeout=120)
d = sqlite3.connect(dst)
s.backup(d)
d.close(); s.close()
t1 = time.time()
q = sqlite3.connect("file:%s?mode=ro" % dst, uri=True).execute("PRAGMA quick_check").fetchone()[0]
print(json.dumps({"t_snapshot": t0, "t_done": t1, "quick_check": q}))' "$lab" 2>&1 | tail -1)
    case "$res" in "{"*'"quick_check": "ok"'*) [ -s "$dst.part" ] && break ;; esac
    note "  snapshot $lab outside the hub, try $try failed: $(printf '%s' "$res" | cut -c1-200)"; rm -f "$dst.part"; res=""
    wsleep 5
  done
  if [ -n "$res" ]; then
    mv "$dst.part" "$dst"
    t0=$("$PY" -c "import json,sys;print(repr(json.loads(sys.argv[1])['t_snapshot']))" "$res")
    t1=$("$PY" -c "import json,sys;print(repr(json.loads(sys.argv[1])['t_done']))" "$res")
    qc='"ok"'
  else
    method=hub_tmp_fallback
    t0=$("$PY" -c 'import time;print(repr(time.time()))')
    if ! docker exec "$HUB" python3 -c "import sqlite3;s=sqlite3.connect('file:/config/home-assistant_v2.db?mode=ro',uri=True,timeout=120);d=sqlite3.connect('/tmp/e9_snap.db');s.backup(d);d.close();s.close()" >/dev/null 2>&1; then
      note "  snapshot $lab FAILED"; ev snapshot "\"label\": \"$lab\", \"ok\": false"; return 1
    fi
    t1=$("$PY" -c 'import time;print(repr(time.time()))')
    docker cp "$HUB:/tmp/e9_snap.db" "$dst" >/dev/null; docker exec "$HUB" rm -f /tmp/e9_snap.db
  fi
  local info; info=$("$PY" -c "
import sqlite3,sys,json;c=sqlite3.connect('file:'+sys.argv[1]+'?mode=ro',uri=True)
q=lambda s:c.execute(s).fetchone()
print(json.dumps({'states':q('select count(*),min(last_updated_ts),max(last_updated_ts),max(state_id) from states'),
 'events':q('select count(*),min(time_fired_ts),max(time_fired_ts),max(event_id) from events'),
 'statistics_runs_min_start':q('select min(start) from statistics_runs')[0],'recorder_runs':q('select count(*),min(run_id),max(run_id) from recorder_runs')}))" "$dst")
  ev snapshot "\"label\": \"$lab\", \"ok\": true, \"method\": \"$method\", \"quick_check\": $qc, \"t_snapshot\": $t0, \"t_done\": $t1, \"file\": \"snapshots/$lab.db\", \"sha256\": \"$(shasum -a 256 "$dst" | cut -d' ' -f1)\", \"bytes\": $(stat -f %z "$dst"), \"db\": $info"
  note "  snapshot $lab ($method): $(stat -f %z "$dst") bytes, $(s16 "$dst"), at $(date -u -r ${t0%.*} +%FT%TZ)"
}

