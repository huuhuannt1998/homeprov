SCRATCH_MODE=${HPR_E9_SCRATCH:-0}
SMOKE=${HPR_E9_SMOKE:-0}
RESTART_WAIT=${HPR_E9_RESTART_WAIT:-45}
NOT_BEFORE=${HPR_E9_NOT_BEFORE:-1791608400}             # 2026-10-10T05:00:00Z: the E2 night owns hpr-* until then

# ---- run parameters (pre-registered: drafts/round13/E9_PREREG_DRAFT.json) ----------------------------------------
TAG=${1:?usage: run_e9.sh TAG}
START=${HPR_E9_START:-2026-10-11T12:00:00Z}
DAYS=${HPR_E9_DAYS:-7}
TRIALS=${HPR_E9_TRIALS:-5}                              # per arm per daily batch
EC_ARMS=${HPR_E9_EC_ARMS:-PU PSR}
E7_ARMS=${HPR_E9_E7_ARMS:-INS-L BD-S}
K=${HPR_E9_K:-9}
SEAL_WAIT_S=${HPR_E9_SEAL_WAIT_S:-130}
BD_LOOKBACK_S=${HPR_E9_BD_LOOKBACK_S:-1800}
BD_MIN_AGE_S=${HPR_E9_BD_MIN_AGE_S:-130}
PERIOD=${HPR_E9_PERIOD:-5}
KEEP_DAYS=${HPR_E9_KEEP_DAYS:-30}                       # the hub's purge_keep_days (checked against its configuration)
SMOKE_KEEP_DAYS=${HPR_E9_SMOKE_KEEP_DAYS:-29}           # forced purge of the smoke run (scratch hub only)
SMOKE_DAY_S=${HPR_E9_SMOKE_DAY_S:-1080}
MIN_SETUP_S=${HPR_E9_MIN_SETUP_S:-3600}                 # real run: at least this long between the script's start and START
RENAME_ENTITY=${HPR_E9_RENAME_ENTITY:-light.porch_light}
UNLINKED_PERSON=${HPR_E9_UNLINKED_PERSON:-Jordan Rivera (household)}   # a person with no account: the person move's target
MOVE_ACCOUNT=${HPR_E9_MOVE_ACCOUNT:-Alex Rivera (household)}           # the account the move takes (if present)
RENAME_TO=${HPR_E9_RENAME_TO:-Porch lamp}
NAMEMAP_STEP_S=${HPR_E9_NAMEMAP_STEP_S:-60}             # between name-map steps (the hub saves .storage after <= 10 s)
NAMEMAP_ATTACK_HOLD_S=${HPR_E9_NAMEMAP_ATTACK_HOLD_S:-180}
MARKER_LEAD_S=${HPR_E9_MARKER_LEAD_S:-30}               # a declared change waits this long after its marker is anchored
PURGE_GUARD_LO=${HPR_E9_PURGE_GUARD_LO:-0350}           # no hub restart in [03:50, 04:45) UTC (real mode)
PURGE_GUARD_HI=${HPR_E9_PURGE_GUARD_HI:-0445}
SLEEP_GUARD_S=${HPR_E9_SLEEP_GUARD_S:-30}               # restart the hub at 03:40 if its purge timer is later than this
LATE_BOUND_S=${HPR_E9_LATE_BOUND_S:-30}                 # verifier parameters, as E7/E8
GAP_S=${HPR_E9_GAP_S:-30}
WPORT_D=${HPR_E9_WITNESS_PORT_DIRECT:-19980}
WPORT_C=${HPR_E9_WITNESS_PORT_COPY:-19981}
# Monitor settings of the E9 code (drafts/round13/E9_IMPL_NOTES.md section 8): HOMEPROV_READ (A4, copy|direct),
# HOMEPROV_SINCE=0 (A5, full-history initial seal, streamed one hour at a time), HOMEPROV_ROWBIND=1 (A2, per-row keylog
# binding), HOMEPROV_KEYLOG_REWIND=1 (review R6: after a restore the keylog restarts at the backup's last key, so rows
# written with reused keys are bound at first observation), HOMEPROV_QUICK_CHECK_EVERY per monitor (pre-registered, lead
# 2026-10-10): M-direct 720 (once an hour at 5 s polls: in direct mode quick_check reads the whole live database inside
# the read transaction and holds a checkpoint's backfill off for that long, while the per-poll consistency check -- WAL
# salts, checkpoint sequence, change counter, read_raced -- catches a torn read at every poll); M-copy 1 (every poll, as
# E8's copy path did).
QC_DIRECT_PREREG=720; QC_COPY_PREREG=1
QUICK_CHECK_DIRECT=${HPR_E9_QUICK_CHECK_DIRECT:-$QC_DIRECT_PREREG}
QUICK_CHECK_COPY=${HPR_E9_QUICK_CHECK_COPY:-$QC_COPY_PREREG}
MON_DIRECT_ENV=${HPR_E9_DIRECT_ENV:-HOMEPROV_READ=direct HOMEPROV_QUICK_CHECK_EVERY=$QUICK_CHECK_DIRECT}
MON_COPY_ENV=${HPR_E9_COPY_ENV:-HOMEPROV_READ=copy HOMEPROV_QUICK_CHECK_EVERY=$QUICK_CHECK_COPY}
MON_FULL_ENV=${HPR_E9_FULL_HISTORY_ENV:-HOMEPROV_SINCE=0}
MON_EXTRA_ENV=${HPR_E9_EXTRA_MON_ENV-HOMEPROV_ROWBIND=1 HOMEPROV_KEYLOG_REWIND=1}
VERIFY_JOBS=${HPR_E9_VERIFY_JOBS:-2}                     # scorer: verifications in parallel, on the HOST after the freeze
RESTORE_TOL_S=${HPR_E9_RESTORE_TOL_S:-30}                # verifier parameters (pre-registered)
RESTORE_MAX_AGE_S=${HPR_E9_RESTORE_MAX_AGE_S:-86400}
PURGE_TOL_S=${HPR_E9_PURGE_TOL_S:-60}
RESTORE_DONE_MAX_S=${HPR_E9_RESTORE_DONE_MAX_S:-600}     # a RESTORE excuses nothing without its RESTORE_DONE within this (N1)
NEED_E9_CODE=${HPR_E9_NEED_E9_CODE:-$([ "$SCRATCH_MODE" = "1" ] && echo 0 || echo 1)}
PY=$(command -v python3); [ -n "$PY" ] || { echo "python3 not found"; exit 4; }

SP=${HPR_E9_SP:-<research-dir>/HOMEPROV-P13-exp/e9/$TAG}
AD=${PREFIX}-anchord-direct; MD=${PREFIX}-monitor-direct
AC=${PREFIX}-anchord-copy;   MC=${PREFIX}-monitor-copy
WNET=${PREFIX}-$TAG-wnet
V=${PREFIX}-$TAG
VOLS="$V-direct-chain $V-direct-pub $V-direct-scratch $V-direct-sign $V-copy-chain $V-copy-pub $V-copy-scratch $V-copy-sign $V-operator"
META=$SP/auth_meta.log
EVLOG=$SP/events.jsonl
MK=/config/homeprov_out
OPS="$REPO/testbed/e9/e9ops.py"

# ---- refusals (nothing is created before these pass) ------------------------------------------------------------
[ -e "$SP" ] && { echo "REFUSING: $SP exists"; exit 3; }
ls "$OUT/${TAG}_"* >/dev/null 2>&1 && { echo "REFUSING: outputs $OUT/${TAG}_* exist"; exit 3; }
for c in $AD $MD $AC $MC; do
  docker ps -a --format '{{.Names}}' | grep -qx "$c" && { echo "REFUSING: container $c exists"; exit 3; }
done
for v in $VOLS; do docker volume inspect "$v" >/dev/null 2>&1 && { echo "REFUSING: volume $v exists"; exit 3; }; done
docker network inspect "$WNET" >/dev/null 2>&1 && { echo "REFUSING: network $WNET exists"; exit 3; }
for p in $WPORT_D $WPORT_C; do
  lsof -nP -iTCP:$p -sTCP:LISTEN >/dev/null 2>&1 && { echo "REFUSING: port $p is in use"; exit 3; }
done

e2_night_running() {   # 0 (true) while an E2 night runs: an e2-issuer* container RUNNING, or a driver process alive
  docker ps --format '{{.Names}}' | grep -q '^e2-issuer' && { echo "an e2-issuer container is running"; return 0; }
  local pid cwd
  for pid in $(pgrep -f 'driver_oct[0-9]*\.sh|e2night/driver\.sh|e2_night\.py' 2>/dev/null); do
    echo "E2-night process $pid ($(ps -o command= -p "$pid" 2>/dev/null | cut -c1-80)) is running"; return 0
  done
  for pid in $(pgrep -f 'driver.*\.sh' 2>/dev/null); do
    cwd=$(lsof -a -p "$pid" -d cwd -Fn 2>/dev/null | sed -n 's/^n//p')
    case "$cwd" in *e2night*) echo "process $pid runs in $cwd"; return 0 ;; esac
  done
  return 1
}

START_TS=$("$PY" -c "import sys;sys.path.insert(0,sys.argv[1]);import e9ops;print(int(e9ops.parse_iso(sys.argv[2])))" "$REPO/testbed/e9" "$START")

preflight() {
  echo "== E9 preflight =="
  case "$MON_IMG $ANC_IMG" in *hpr-monitor:1*|*hpr-anchord:1*|*:sig*|*:linked*|*:e7*|*:e8*)
    echo "  FAIL refusing to build or use the image tags of earlier runs ($MON_IMG, $ANC_IMG); use new tags"; exit 2 ;; esac
  docker info >/dev/null 2>&1 || { echo "  FAIL docker daemon down"; exit 1; }
  if [ "$SCRATCH_MODE" != "1" ]; then
    [ "$SMOKE" = "1" ] && { echo "  FAIL HPR_E9_SMOKE=1 needs HPR_E9_SCRATCH=1 (the forced purge never runs on the real hub)"; exit 2; }
    local now why; now=$(date -u +%s)
    [ "$now" -lt "$NOT_BEFORE" ] && { echo "  FAIL it is $(date -u +%FT%TZ); the E2 night owns the default deployment until $(date -u -r "$NOT_BEFORE" +%FT%TZ)"; exit 2; }
    if why=$(e2_night_running); then echo "  FAIL the E2 night is running ($why)"; exit 2; fi
    echo "  ok    E2 night not running; clock past $(date -u -r "$NOT_BEFORE" +%FT%TZ)"
    [ $((START_TS - now)) -lt "$MIN_SETUP_S" ] && { echo "  FAIL START $START is less than ${MIN_SETUP_S}s away (setup and the full-history seal need the time); set HPR_E9_START"; exit 2; }
    echo "  ok    START $START is $(( (START_TS - now) / 60 )) min away"
    local pw; pw=$(pmset -g batt | head -1)
    case "$pw" in *"AC Power"*) echo "  ok    on AC power" ;; *) echo "  FAIL not on AC power ($pw): the Mac must stay on power for seven days"; exit 2 ;; esac
    local lid; lid=$(ioreg -r -k AppleClamshellState -d 4 2>/dev/null | grep AppleClamshellState | head -1)
    case "$lid" in *Yes*) echo "  FAIL the lid is closed ($lid): a closed lid sleeps the Mac"; exit 2 ;; *) echo "  ok    lid open ($lid)" ;; esac
    grep -q "purge_keep_days: $KEEP_DAYS" <(docker exec "$HUB" cat /config/configuration.yaml) \
      || { echo "  FAIL the hub's configuration.yaml does not say purge_keep_days: $KEEP_DAYS"; exit 2; }
    docker exec "$HUB" grep -q '^ *auto_purge: *false' /config/configuration.yaml && { echo "  FAIL auto_purge is off"; exit 2; }
    echo "  ok    purge_keep_days $KEEP_DAYS, auto_purge on (default)"
  else
    case " $HUB $DEVICES $BROKER $STOCK_MON $STOCK_ANC $PREFIX " in *" hpr-"*|*" e2-"*|*" e9 "*)
      echo "  FAIL scratch mode with a default-deployment target ($HUB $DEVICES $BROKER $STOCK_MON $STOCK_ANC, prefix $PREFIX)"; exit 2 ;; esac
    case "$CFGVOL $NET $OUT" in *homeprov-real*|*"$REPO/exp/out"*)
      echo "  FAIL scratch mode with the default deployment's volume or network, or outputs in exp/out ($CFGVOL, $NET, $OUT)"; exit 2 ;; esac
    echo "  skip  E2-night, clock, start-time and power guards (scratch mode; no default-deployment target)"
  fi
  for c in "$HUB" "$DEVICES" "$BROKER"; do
    docker ps --format '{{.Names}}' | grep -qx "$c" || { echo "  FAIL $c is not running"; exit 2; }
  done
  echo "  ok    hub ($HUB), devices ($DEVICES) and broker ($BROKER) up"
  for comp in homeprov_ec homeprov_e7; do
    [ -f "$CC/$comp/__init__.py" ] || { echo "  FAIL no $comp under $CC"; exit 2; }
  done
  [ -f "$E6_SRC/__init__.py" ] || { echo "  FAIL no homeprov_e6 at $E6_SRC"; exit 2; }
  docker exec "$HUB" sh -c "grep -qE '^homeprov_(ec|e7|e6):' /config/configuration.yaml || test -e /config/custom_components/homeprov_ec || test -e /config/custom_components/homeprov_e7" \
    && { echo "  FAIL the hub lists or holds an attack integration (leftover of an earlier run)"; exit 2; }
  if [ "${HPR_E9_RUN_TESTS:-1}" = "1" ]; then
    if ! ( cd "$REPO" && "$PY" -m pytest -q monitor ) > "/tmp/hpr_e9_${TAG}_pytest_mon.log" 2>&1; then
      echo "  FAIL monitor tests fail ($(tail -2 /tmp/hpr_e9_${TAG}_pytest_mon.log | tr '\n' ' '))"; exit 2
    fi
    echo "  ok    monitor tests pass ($(tail -1 /tmp/hpr_e9_${TAG}_pytest_mon.log))"
    if ! ( cd "$REPO" && "$PY" -m pytest -q testbed/anchord ) > "/tmp/hpr_e9_${TAG}_pytest_anc.log" 2>&1; then
      echo "  FAIL anchor tests fail ($(tail -2 /tmp/hpr_e9_${TAG}_pytest_anc.log | tr '\n' ' '))"; exit 2
    fi
    echo "  ok    anchor tests pass ($(tail -1 /tmp/hpr_e9_${TAG}_pytest_anc.log))"
  fi
  if [ "${HPR_E9_BUILD_IMAGES:-1}" = "1" ]; then
    docker build -q -f "$REPO/monitor/Dockerfile.sign" -t "$MON_IMG" "$REPO/monitor" >/dev/null \
      || { echo "  FAIL docker build $MON_IMG (monitor/Dockerfile.sign)"; exit 2; }
    docker build -q -f "$REPO/testbed/e8/anchord-e8.Dockerfile" -t "$ANC_IMG" "$REPO/testbed/anchord" >/dev/null \
      || { echo "  FAIL docker build $ANC_IMG"; exit 2; }
    echo "  ok    built $MON_IMG (monitor/Dockerfile.sign) and $ANC_IMG (testbed/e8/anchord-e8.Dockerfile)"
  fi
  for img in "$MON_IMG" "$ANC_IMG"; do docker image inspect "$img" >/dev/null 2>&1 || { echo "  FAIL image $img missing"; exit 2; }; done
  local f repo_h img_h bad=0
  for f in "monitor/monitor.py|$MON_IMG|/app/monitor.py" "testbed/anchord/anchord.py|$ANC_IMG|/app/anchord.py" \
           "testbed/anchord/anchord_linked.py|$ANC_IMG|/app/anchord_linked.py"; do
    local rp=${f%%|*} rest=${f#*|}; local img=${rest%%|*} ip=${rest#*|}
    repo_h=$(shasum -a 256 "$REPO/$rp" | cut -d' ' -f1)
    img_h=$(docker run --rm --entrypoint sha256sum "$img" "$ip" 2>/dev/null | cut -d' ' -f1)
    if [ "$repo_h" != "$img_h" ]; then echo "  FAIL $img:$ip sha $img_h != repository $rp $repo_h"; bad=1
    else echo "  ok    $img:$ip = repository $rp (${repo_h:0:16})"; fi
  done
  [ $bad -eq 0 ] || exit 2
  local need
  need=$(docker run --rm --entrypoint sh "$MON_IMG" -c "for k in HOMEPROV_COVERAGE seq_local HOMEPROV_SIGN_KEY HOMEPROV_REPLY_TAGS HOMEPROV_ESCROW_DIR HOMEPROV_COST_LOG HOMEPROV_NAMEMAP_DIR; do grep -q \$k /app/monitor.py || echo \$k; done")
  [ -z "$need" ] && echo "  ok    $MON_IMG has coverage, signatures, reply tags, escrow, cost log, name map" \
    || { echo "  FAIL $MON_IMG lacks: $need"; exit 2; }
  # The E9 code (part A). TODO(E9): replace these names by those in drafts/round13/E9_IMPL_NOTES.md.
  local e9need=""
  for kv in $MON_DIRECT_ENV $MON_FULL_ENV $MON_EXTRA_ENV; do
    docker run --rm --entrypoint grep "$MON_IMG" -q "${kv%%=*}" /app/monitor.py || e9need="$e9need ${kv%%=*}"
  done
  if [ -n "$e9need" ]; then
    if [ "$NEED_E9_CODE" = "1" ]; then echo "  FAIL $MON_IMG lacks the E9 settings:$e9need (part A not landed)"; exit 2
    else echo "  WARN $MON_IMG lacks the E9 settings:$e9need (part A not landed): the monitors run as in E8 for those"; fi
  else echo "  ok    $MON_IMG reads $MON_DIRECT_ENV, $MON_FULL_ENV and $MON_EXTRA_ENV"; fi
  for fn in scoped_marker restore_marker rename_marker load_signer "def issue" backup_wm new_nonce; do
    grep -q "$fn" "$REPO/exp/rig/marker_issuer.py" || { echo "  FAIL exp/rig/marker_issuer.py lacks $fn (E9 A6)"; exit 2; }
  done
  echo "  ok    exp/rig/marker_issuer.py has the E9 operator issuer (signed markers, reply tags, RESTORE, RENAME)"
  # review N1: RESTORE_DONE in the issuer and --restore-done-max-s in the verifier (real run refuses without them)
  local n1=""
  grep -q "restore_done_marker" "$REPO/exp/rig/marker_issuer.py" || n1="$n1 issuer:restore_done_marker"
  grep -q -- "--restore-done-max-s" "$REPO/exp/stages/e7_verify.py" || n1="$n1 verifier:--restore-done-max-s"
  if [ -n "$n1" ]; then
    if [ "$SCRATCH_MODE" = "1" ]; then echo "  WARN RESTORE_DONE support missing:$n1 [scratch]"
    else echo "  FAIL RESTORE_DONE support missing:$n1"; exit 2; fi
  else echo "  ok    RESTORE_DONE in the issuer and --restore-done-max-s in the verifier"; fi
  E9_CODE_MISSING="$e9need"
  # quick_check cadence per monitor: exactly one HOMEPROV_QUICK_CHECK_EVERY in each monitor's settings, a positive
  # integer, equal to the pre-registered value (real mode refuses otherwise; scratch warns)
  local m envs qc want
  for m in direct copy; do
    if [ $m = direct ]; then envs=$MON_DIRECT_ENV; want=$QC_DIRECT_PREREG; else envs=$MON_COPY_ENV; want=$QC_COPY_PREREG; fi
    qc=$(printf '%s\n' $envs | sed -n 's/^HOMEPROV_QUICK_CHECK_EVERY=//p')
    if [ "$(printf '%s\n' $envs | grep -c '^HOMEPROV_QUICK_CHECK_EVERY=')" != "1" ] || ! [[ "$qc" =~ ^[1-9][0-9]*$ ]]; then
      echo "  FAIL M-$m: HOMEPROV_QUICK_CHECK_EVERY must be set once to a positive integer ([$envs])"; exit 2
    fi
    if [ "$qc" != "$want" ]; then
      if [ "$SCRATCH_MODE" = "1" ]; then echo "  WARN M-$m: HOMEPROV_QUICK_CHECK_EVERY=$qc, pre-registered $want [scratch]"
      else echo "  FAIL M-$m: HOMEPROV_QUICK_CHECK_EVERY=$qc, pre-registered $want"; exit 2; fi
    else echo "  ok    M-$m: HOMEPROV_QUICK_CHECK_EVERY=$qc (pre-registered)"; fi
  done
  docker run --rm --entrypoint grep "$MON_IMG" -q HOMEPROV_QUICK_CHECK_EVERY /app/monitor.py \
    || { echo "  FAIL $MON_IMG does not read HOMEPROV_QUICK_CHECK_EVERY"; exit 2; }
  MON_CRYPTO=$(docker run --rm --entrypoint python "$MON_IMG" -c "import cryptography;print(cryptography.__version__)" 2>&1 | tail -1)
  case "$MON_CRYPTO" in [0-9]*) echo "  ok    $MON_IMG has cryptography $MON_CRYPTO" ;;
    *) echo "  FAIL $MON_IMG cannot import cryptography ($MON_CRYPTO)"; exit 2 ;; esac
  need=$(docker run --rm --entrypoint sh "$ANC_IMG" -c "for k in HOMEPROV_OPERATOR_KEY X-HP-Reply-Auth; do grep -q \$k /app/anchord.py || echo \$k; done; grep -q records_pushed /app/anchord_linked.py || echo extension-pushes")
  [ -z "$need" ] && echo "  ok    $ANC_IMG has the operator key, tagged replies and extension pushes" \
    || { echo "  FAIL $ANC_IMG lacks: $need"; exit 2; }
  grep -q not_extension "$REPO/testbed/anchord/headwitness.py" && echo "  ok    headwitness.py checks extension records" \
    || { echo "  FAIL headwitness.py does not check that a head extends the last one"; exit 2; }
}
preflight

mkdir -p "$SP/keys" "$SP/escrow_direct" "$SP/escrow_copy" "$SP/witness_direct" "$SP/witness_copy" "$SP/code" \
