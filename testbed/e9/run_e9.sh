E6_SRC=${HPR_E9_E6_SRC:-<research-dir>/HOMEPROV-P13-exp/e6/code/homeprov_e6}   # E6 in-hub harness (never released)
HUB=${HPR_E9_HUB:-hpr-hass}
NET=${HPR_E9_NET:-homeprov-real_hp-real}
CFGVOL=${HPR_E9_CFGVOL:-homeprov-real_hpr-config}
